"""
send_cold_mail.py — Option B: send cold emails to recruiters you specify.

By default, pulls from `recruiters.csv` (auto-created from a sample).
Reads `name, email, role, post_text` per row and sends a personalized
cold email generated by Ollama (gemma4:31b-cloud is the recommended model).

Usage:
  # 1. From a CSV file (header: name,email,role,post_text):
  python send_cold_mail.py --csv recruiters.csv --dry-run

  # 2. Single recipient:
  python send_cold_mail.py --to priya.s@infosys.com --name "Priya Sharma" --role "Python Developer"

  # 3. Single recipient with custom post text:
  python send_cold_mail.py --to priya.s@infosys.com --name "Priya Sharma" \
        --role "Full Stack Developer" --post-text "We are hiring at Infosys for..."

  # 4. Multi-recipient interactive (you'll be prompted per row):
  python send_cold_mail.py --interactive

CSV columns (header required, order flexible):
  - name       (required) — recruiter name
  - email      (required) — recruiter email
  - role       (optional) — role they're hiring for; falls back to "Python Developer"
  - post_text  (optional) — body of their LinkedIn post; if missing, generic

Recommended setup:
  - Set OLLAMA_MODEL=gemma4:31b-cloud in .env (fast cloud model)
  - Or use qwen2.5-coder:7b if you want to keep emails offline

Safety:
  - Server-side daily limit: 15/day (DAILY_PERSONAL_CAP in .env)
  - Per-run cap: 10 (override with --limit)
  - DRY-RUN IS THE DEFAULT (use --send to actually deliver)
  - Tracks last_send_at; 60-180s random delay between sends
"""
import argparse
import csv
import json
import os
import random
import sys
import time
from pathlib import Path

PROJ_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(PROJ_DIR))

# Load .env from project root
from dotenv import load_dotenv
load_dotenv(PROJ_DIR / ".env")

import mailer
import composer


SENT_LOG = PROJ_DIR / "sent_log.jsonl"
DEFAULT_CSV = PROJ_DIR / "recruiters.csv"


# ── Helpers ───────────────────────────────────────────────────────────────────

def log_sent(entry: dict):
    """Append to a JSONL log of every send attempt."""
    with open(SENT_LOG, "a", encoding="utf-8") as f:
        f.write(json.dumps(entry) + "\n")


def safe_int_env(name: str, default: int) -> int:
    v = os.getenv(name)
    if not v:
        return default
    try:
        return int(v)
    except ValueError:
        return default


def make_recruiter(name, email, role="Python/Django Developer", post_text=""):
    return {
        "name": name.strip(),
        "email": email.strip().lower(),
        "role": role.strip() or "Python/Django Developer",
        "post_text": post_text.strip(),
    }


def send_one(recruiter, dry_run, attachment):
    """Generate + send one cold email. Returns True on success."""
    print(f"\n{'=' * 56}\n  → {recruiter['name']} <{recruiter['email']}>\n  role: {recruiter['role']}\n{'=' * 56}")

    # Generate email body via composer.py (already has fallback chain)
    post_text = recruiter["post_text"] or (
        f"Hiring for a {recruiter['role']} role. Please reach out if interested."
    )
    body = composer.generate_cold_email(post_text, recruiter["name"])

    if not body:
        # Composer failed entirely — build a minimum-viable canned body
        body = (
            f"Hi {recruiter['name']},\n\n"
            f"I came across your post about the {recruiter['role']} role and wanted to express my interest. "
            f"I'm an MCA student specializing in Python/Django/AI/ML, graduating in 2026. "
            f"Resume attached for your review.\n\n"
            f"Would a 15-minute call this week work for an initial chat?\n\n"
            f"Best,\nVenu"
        )
        print(f"  ⚠ composer returned None — using canned fallback body")

    subject = f"Interest in {recruiter['role']} role"

    if dry_run:
        print(f"  [DRY-RUN] body preview ({len(body)} chars):")
        for line in body.split("\n")[:3]:
            print(f"    {line[:80]}")
        print(f"  [DRY-RUN] would send to {recruiter['email']}")
        log_sent({
            "ts": time.time(),
            "name": recruiter["name"],
            "email": recruiter["email"],
            "role": recruiter["role"],
            "status": "dry-run",
            "subject": subject,
            "body_len": len(body),
        })
        return True  # dry-run counts as success

    ok = mailer.send_email(recruiter["email"], subject, body, attachment)
    log_sent({
        "ts": time.time(),
        "name": recruiter["name"],
        "email": recruiter["email"],
        "role": recruiter["role"],
        "status": "sent" if ok else "failed",
        "subject": subject,
        "body_len": len(body),
    })
    if ok:
        print(f"  ✅ sent to {recruiter['email']}")
    else:
        print(f"  ❌ FAILED to send to {recruiter['email']}")
    return ok


def load_csv(path: Path):
    """Yield recruiter dicts from CSV. Required columns: name, email."""
    if not path.exists():
        return
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            print(f"  ⚠ {path} has no header / is empty")
            return
        missing_cols = [c for c in ("name", "email") if c not in reader.fieldnames]
        if missing_cols:
            print(f"  ❌ {path} missing required columns: {missing_cols}")
            return
        for row in reader:
            if not row.get("email"):
                continue
            yield make_recruiter(
                name=row.get("name", "Hiring Manager"),
                email=row["email"],
                role=row.get("role", ""),
                post_text=row.get("post_text", ""),
            )


def write_csv_template(path: Path):
    """Create a sample CSV with the right columns for the user to fill."""
    if path.exists():
        return
    sample = [
        ["name", "email", "role", "post_text"],
        ["Sarah Chen", "sarah.chen@example.com", "Backend Developer", "We're hiring a backend dev for our fintech. Python/Django required, plus AI/ML a plus."],
        ["Priya Sharma", "priya.sharma@example.in", "Full Stack AI Engineer", "Hiring Full Stack AI Engineer at our Bangalore office. MCA freshers encouraged."],
        ["", "", "", ""],  # blank rows are skipped
        ["# Notes:", "", "", ""],
        ["# - name: required", "", "", ""],
        ["# - email: required", "", "", ""],
        ["# - role: optional (default: Python/Django Developer)", "", "", ""],
        ["# - post_text: optional; if blank a generic body is used", "", "", ""],
    ]
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerows(sample)
    print(f"  📝 created sample CSV at {path}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser(description="Send cold emails to recruiters (Option B)")
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--csv",        help="Path to CSV with recruiter list (columns: name, email, role, post_text)")
    src.add_argument("--to",         help="Single recruiter email")
    src.add_argument("--interactive", action="store_true", help="Prompt for recruiters one at a time")

    ap.add_argument("--name",       help="Recruiter name (required for --to)")
    ap.add_argument("--role",       help="Role they're hiring for")
    ap.add_argument("--post-text",  help="LinkedIn post text (verbatim or paraphrased) for personalization")
    ap.add_argument("--send",       action="store_true",
                    help="Actually send (default is dry-run, which previews only)")
    ap.add_argument("--limit",      type=int, default=None,
                    help="Override per-run send limit (default 10 or DAILY_PERSONAL_CAP)")
    args = ap.parse_args()

    if args.to and not args.name:
        ap.error("--to requires --name")

    # Build recruiter queue
    recruiters = []
    if args.csv:
        path = Path(args.csv)
        if not path.exists():
            print(f"❌ CSV not found: {path}")
            # Always write the sample to DEFAULT_CSV (not to user's broken path)
            if path.resolve() != DEFAULT_CSV.resolve():
                write_csv_template(DEFAULT_CSV)
                print(f"  Auto-generated sample: {DEFAULT_CSV}")
                print(f"  Fill it in and re-run: python send_cold_mail.py --csv {DEFAULT_CSV}")
            else:
                write_csv_template(DEFAULT_CSV)
            return 1
        recruiters.extend(load_csv(path))
    elif args.to:
        recruiters.append(make_recruiter(
            name=args.name,
            email=args.to,
            role=args.role or "",
            post_text=args.post_text or "",
        ))
    elif args.interactive:
        print("Interactive mode. Enter one recruiter per line. End with empty name OR Ctrl+C.")
        while True:
            try:
                name = input("\n  Recruiter name (empty to stop): ").strip()
                if not name:
                    break
                email = input("  Email: ").strip()
                if not email:
                    print("  skipping (no email)")
                    continue
                role = input("  Role [Python/Django Developer]: ").strip()
                post_text = input("  Post text (optional): ").strip()
                recruiters.append(make_recruiter(name, email, role, post_text))
            except (KeyboardInterrupt, EOFError):
                break

    # Filter invalid rows
    recruiters = [r for r in recruiters if r["email"] and "@" in r["email"]]
    if not recruiters:
        print("No valid recruiters to process.")
        return 1

    # Caps
    per_run_cap   = args.limit if args.limit is not None else 10
    daily_cap     = safe_int_env("DAILY_PERSONAL_CAP", 15)
    already_sent  = sum(1 for line in open(SENT_LOG) if '"status": "sent"' in line) if SENT_LOG.exists() else 0
    remaining_day = max(0, daily_cap - already_sent)

    print(f"\n📬 Cold-mail bot — mode: {'LIVE' if args.send else 'DRY-RUN'}")
    print(f"  recruiters queued:  {len(recruiters)}")
    print(f"  per-run cap:        {per_run_cap}")
    print(f"  daily cap:          {daily_cap} (already sent: {already_sent}, remaining: {remaining_day})")
    print(f"  ollama model:       {os.getenv('OLLAMA_MODEL', 'phi4-mini:latest')}")
    print(f"  resume path:        {os.getenv('RESUME_PATH', '(not set)')}")
    print(f"  delay between:      60–180s (random)")

    attachment = os.getenv("RESUME_PATH")
    if not args.send and not (attachment and Path(attachment).exists()):
        print(f"\n  ⚠ resume not found at {attachment!r}; sends will be skipped or body-only")

    sent = 0
    failed = 0
    for idx, rec in enumerate(recruiters):
        if sent >= per_run_cap:
            print(f"\n  ✋ per-run cap ({per_run_cap}) reached")
            break
        if sent >= remaining_day:
            print(f"\n  ✋ daily cap ({daily_cap}) reached; wait until tomorrow")
            break

        ok = send_one(rec, dry_run=not args.send, attachment=attachment)
        if ok:
            sent += 1
        else:
            failed += 1

        # Cooldown between sends
        if idx < len(recruiters) - 1 and sent < per_run_cap:
            delay = random.uniform(60, 180)
            print(f"  ⏸ cooldown {delay:.0f}s...")
            time.sleep(delay)

    print(f"\n{'=' * 56}")
    print(f"  Personal emails: {sent} sent, {failed} failed, {len(recruiters) - sent - failed} skipped")
    print(f"  Log: {SENT_LOG}")
    print(f"{'=' * 56}\n")
    return 0 if failed == 0 else 2


if __name__ == "__main__":
    sys.exit(main())
